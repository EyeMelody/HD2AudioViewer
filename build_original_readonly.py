"""Generate a read-only fork from selected upstream UI/parser code, not runtime monkey patches."""
import ast
from pathlib import Path
ROOT = Path(__file__).parent

TRANSLATIONS = {
 'File':'文件','Type':'类型','Sources':'音频源','Hierarchy':'层级结构',
 'Archive File':'归档文件','Sound Bank':'音频库','Text Bank':'文本库',
 'Audio Source':'音频源','Event':'事件','String':'文本','Music Track':'音乐轨道',
 'Music Segment':'音乐片段','Random Sequence':'随机序列','Bink Video':'视频',
 'Now Playing: ':'正在播放：','Now Playing:':'正在播放：',
 'Event ':'事件 ','Track ':'轨道 ','Segment ':'片段 ','Sequence ':'序列 ','Video ':'视频 ',
 'Segoe UI':'Microsoft YaHei UI',
}
class Translate(ast.NodeTransformer):
    def visit_Constant(self,node):
        if isinstance(node.value,str) and node.value in TRANSLATIONS:
            node.value=TRANSLATIONS[node.value]
        return node

tree = ast.parse((ROOT/'core.py').read_text(encoding='utf-8'))
class ReadImports(ast.NodeTransformer):
    def visit_Import(self,node):
        for a in node.names:
            if a.name in ('wwise_hierarchy_140','wwise_hierarchy_154'):
                a.asname=a.name; a.name='readonly_'+a.name
        return node
    def visit_ImportFrom(self,node):
        if node.module in ('wwise_hierarchy_140','wwise_hierarchy_154'):node.module='readonly_'+node.module
        if node.module=='log':node.module='readonly_log'
        return node
for name in ('wwise_hierarchy_140','wwise_hierarchy_154'):
    source=ast.parse((ROOT/(name+'.py')).read_text(encoding='utf-8'))
    (ROOT/('readonly_'+name+'.py')).write_text(ast.unparse(ReadImports().visit(source))+'\n',encoding='utf-8')
kept=[]
for node in tree.body:
    if isinstance(node,ast.ClassDef):
        if node.name in ('Mod','ModHandler','DummyBank'): continue
        node.body=[m for m in node.body if not isinstance(m,(ast.FunctionDef,ast.AsyncFunctionDef)) or not (m.name.startswith(('export','import','revert','write','save','dump')) or m.name in ('to_file','generate'))]
    if isinstance(node,ast.Import):
        for alias in node.names:
            if alias.name=='env': alias.name='readonly_env'; alias.asname='env'
            if alias.name=='log': alias.name='readonly_log'; alias.asname='log'
    if isinstance(node,ast.ImportFrom):
        if node.module=='env': node.module='readonly_env'
        if node.module=='log': node.module='readonly_log'
    kept.append(node)
output=ast.unparse(ReadImports().visit(ast.Module(body=kept,type_ignores=[])))
# Never clean cache files automatically; preview paths are local to this distribution.
output=output.replace('os.remove(self.audio_file)','pass').replace("os.remove(f\"{os.path.join(TMP, filename)}.wem\")",'pass')
output=output.replace("os.remove(f'{os.path.join(TMP, filename)}.wem')",'pass')
output=output.replace('stdout=subprocess.DEVNULL)', 'stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30, creationflags=0x08000000)')
(ROOT/'readonly_core.py').write_text(output+'\n',encoding='utf-8')

tree=ast.parse((ROOT/'audio_modder.py').read_text(encoding='utf-8'))
methods={'create_treeview_entry','create_source_view','create_hierarchy_view','clear_search','recursive_match','search','search_down','search_up','search_bar_on_enter_key','copy_id'}
classes=[]
for node in tree.body:
    if isinstance(node,ast.ClassDef) and node.name in ('ArchiveSearch','AudioPlayerWindow'):
        classes.append(node)
    elif isinstance(node,ast.ClassDef) and node.name=='MainWindow':
        node.bases=[ast.Name(id='ReadOnlyWindow',ctx=ast.Load())]
        node.body=[m for m in node.body if isinstance(m,ast.FunctionDef) and m.name in methods]
        classes.append(node)
generated=ast.unparse(Translate().visit(ast.Module(body=classes,type_ignores=[])))
generated=generated.replace('self.play_button = ttk.Button(', 'self.play_button = IconButton(')
(ROOT/'original_readonly.py').write_text('''# Generated by build_original_readonly.py; upstream UI retained, editing code excluded.
from readonly_ui import *
from readonly_core import *
from tkinterdnd2 import TkinterDnD, DND_FILES
from tkinter import *
from tkinter import ttk
from typing import Callable, Any
import tkinter
import os
import readonly_wwise_hierarchy_140 as wwise_hierarchy_140
import readonly_wwise_hierarchy_154 as wwise_hierarchy_154
language = language_lookup("English (US)")
''' + generated + '''
if __name__ == '__main__':
    window = MainWindow(ArchiveSearch, AudioPlayerWindow)
    window.root.mainloop()
''',encoding='utf-8')
